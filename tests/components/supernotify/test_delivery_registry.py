async def test_expose_entities_hides_transport_without_prerequisites_or_delivery(hass: HomeAssistant) -> None:
    ctx = TestingContext(homeassistant=hass, deliveries={}, transport_types=[TelegramTransport, PersistentTransport])
    await ctx.test_initialize()
    ctx.delivery_registry.expose_entities(ctx.hass_api)

    # telegram has no config entry and no explicit delivery, so no switch
    assert hass.states.get("binary_sensor.supernotify_transport_telegram") is None
    # persistent has no prerequisites to check, so it's always available
    assert hass.states.get("binary_sensor.supernotify_transport_persistent") is not None


async def test_expose_entities_shows_available_transport_even_when_disabled(hass: HomeAssistant) -> None:
    """A transport with real prerequisites still gets a switch while toggled off in
    config, so it can be switched back on - only a genuinely unusable transport is hidden."""
    hass.states.async_set("notify.mock_notify_target", "unknown")
    ctx = TestingContext(
        homeassistant=hass,
        deliveries={},
        transport_types=[NotifyEntityTransport],
        transports={TRANSPORT_NOTIFY_ENTITY: {CONF_ENABLED: False}},
    )
    await ctx.test_initialize()
    ctx.delivery_registry.expose_entities(ctx.hass_api)

    entity_state = hass.states.get("binary_sensor.supernotify_transport_notify_entity")
    assert entity_state is not None
    assert entity_state.state == "off"


async def test_transport_defaults_used_for_missing_service(hass: HomeAssistant, uninitialized_unmocked_config: Context) -> None:
    delivery = {"chatty": {CONF_TRANSPORT: TRANSPORT_GENERIC, CONF_TARGET: ["chan1", "chan2"]}}
    context = uninitialized_unmocked_config
    context.delivery_registry._config_deliveries = delivery
    uut = GenericTransport(context, {CONF_DELIVERY_DEFAULTS: {CONF_ACTION: "notify.slackity"}})
    context.configure_for_tests(transport_instances=[uut])
    await context.initialize()
    await context.delivery_registry.initialize(context)

    await uut.initialize()
    assert list(uut.delivery_registry.deliveries.keys()) == ["chatty"]
    assert uut.delivery_registry.deliveries["chatty"].action == "notify.slackity"
