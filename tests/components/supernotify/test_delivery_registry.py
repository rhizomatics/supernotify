async def test_resolve_name_falls_back_to_default_prefixed_delivery() -> None:
    ctx = TestingContext(deliveries={}, transport_types=[GenericTransport, NotifyEntityTransport])
    await ctx.test_initialize()

    # bare transport name resolves to the auto-configured DEFAULT_-prefixed delivery
    assert ctx.delivery_registry.resolve_name("notify_entity") == "DEFAULT_notify_entity"
    # already-existing name is left untouched
    assert ctx.delivery_registry.resolve_name("DEFAULT_notify_entity") == "DEFAULT_notify_entity"
    # no delivery under either spelling - name is returned unchanged (still not found)
    assert ctx.delivery_registry.resolve_name("no_such_delivery") == "no_such_delivery"


async def test_resolve_name_prefers_a_delivery_named_exactly_that() -> None:
    ctx = TestingContext(deliveries=DELIVERY)
    ctx.add_delivery("notify_entity", TRANSPORT_NOTIFY_ENTITY)
    await ctx.test_initialize()

    # a delivery literally named "notify_entity" exists, so it's preferred over any
    # same-transport DEFAULT_notify_entity that might otherwise have been generated
    assert "DEFAULT_notify_entity" not in ctx.delivery_registry.deliveries
    assert ctx.delivery_registry.resolve_name("notify_entity") == "notify_entity"


